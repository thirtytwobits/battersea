use crate::Result;
use battersea_flow::{document::serialize_canonical_document, FlowDocument};
use serde_json::{json, Value};
use std::{fs, path::Path};

fn type_expression(schema: &Value) -> Result<String> {
    if schema == &Value::Bool(true) {
        return Ok("unknown".into());
    }
    if let Some(reference) = schema.get("$ref").and_then(Value::as_str) {
        return Ok(reference
            .strip_prefix("#/$defs/")
            .ok_or("Only local schema references are supported")?
            .into());
    }
    if let Some(variants) = schema
        .get("oneOf")
        .or_else(|| schema.get("anyOf"))
        .and_then(Value::as_array)
    {
        return Ok(variants
            .iter()
            .map(type_expression)
            .collect::<Result<Vec<_>>>()?
            .join(" | "));
    }
    if let Some(values) = schema.get("enum").and_then(Value::as_array) {
        return Ok(values
            .iter()
            .map(Value::to_string)
            .collect::<Vec<_>>()
            .join(" | "));
    }
    if let Some(value) = schema.get("const") {
        return Ok(value.to_string());
    }
    if let Some(types) = schema.get("type").and_then(Value::as_array) {
        return Ok(types
            .iter()
            .map(|kind| {
                let mut variant = schema.clone();
                variant["type"] = kind.clone();
                type_expression(&variant)
            })
            .collect::<Result<Vec<_>>>()?
            .join(" | "));
    }
    Ok(match schema.get("type").and_then(Value::as_str) {
        Some("string") => "string".into(),
        Some("boolean") => "boolean".into(),
        Some("integer" | "number") => "number".into(),
        Some("null") => "null".into(),
        Some("array") => format!("Array<{}>", type_expression(&schema["items"])?),
        Some("object") => {
            let mut fields = Vec::new();
            if let Some(properties) = schema.get("properties").and_then(Value::as_object) {
                for (name, value) in properties {
                    let required = schema
                        .get("required")
                        .and_then(Value::as_array)
                        .is_some_and(|items| items.iter().any(|item| item == name));
                    fields.push(format!(
                        "{}{}: {}",
                        serde_json::to_string(name)?,
                        if required { "" } else { "?" },
                        type_expression(value)?
                    ));
                }
            }
            match schema.get("additionalProperties") {
                Some(Value::Bool(false)) => {}
                Some(extra) => fields.push(format!("[key: string]: {}", type_expression(extra)?)),
                // An object schema that declares no properties admits any.
                None if fields.is_empty() => fields.push("[key: string]: unknown".into()),
                None => {}
            }
            format!("{{ {} }}", fields.join("; "))
        }
        _ => return Err(format!("Unrepresentable TypeScript schema: {schema}").into()),
    })
}

fn write(root: &Path, file: &str, content: &str, check: bool) -> Result<()> {
    let path = root.join(file);
    if check {
        if fs::read_to_string(&path).ok().as_deref() != Some(content) {
            return Err(format!("{file} is stale; run cargo xtask bindings").into());
        }
    } else {
        fs::create_dir_all(path.parent().unwrap())?;
        fs::write(path, content)?;
    }
    Ok(())
}

pub fn generate(root: &Path, check: bool) -> Result<()> {
    let runtime_schema = battersea_telemetry::schema::contract_schema();
    let mut runtime_types =
        String::from("// Generated by cargo xtask bindings from battersea-telemetry.\n");
    for (name, schema) in runtime_schema["$defs"]
        .as_object()
        .ok_or("Missing runtime definitions")?
    {
        runtime_types.push_str(&format!(
            "export type {name} = {};\n",
            type_expression(schema)?
        ));
    }
    write(
        root,
        "typescript/packages/flow/src/runtime-contract.ts",
        &runtime_types,
        check,
    )?;
    let runtime_schema = serde_json::to_string_pretty(&runtime_schema)? + "\n";
    for path in [
        "crates/battersea-telemetry/schemas/runtime.schema.json",
        "typescript/packages/flow/schemas/runtime.schema.json",
    ] {
        write(root, path, &runtime_schema, check)?;
    }
    let tools_schema = battersea_tools::schema::contract_schema();
    let mut tools_types =
        String::from("// Generated by cargo xtask bindings from battersea-tools.\n");
    for (name, schema) in tools_schema["$defs"]
        .as_object()
        .ok_or("Missing tool definitions")?
    {
        tools_types.push_str(&format!(
            "export type {name} = {};\n",
            type_expression(schema)?
        ));
    }
    write(
        root,
        "typescript/packages/flow/src/tools-contract.ts",
        &tools_types,
        check,
    )?;
    write(
        root,
        "typescript/packages/flow/src/tools-defaults.ts",
        &format!(
            "// Generated by cargo xtask bindings.\nexport const MCP_PROTOCOL_REVISION = {};\nexport const TOOL_PROFILES_META_KEY = {};\n",
            serde_json::to_string(battersea_tools::MCP_PROTOCOL_REVISION)?,
            serde_json::to_string(battersea_tools::PROFILES_META_KEY)?
        ),
        check,
    )?;
    let tools_schema = serde_json::to_string_pretty(&tools_schema)? + "\n";
    for path in [
        "crates/battersea-tools/schemas/tools.schema.json",
        "typescript/packages/flow/schemas/tools.schema.json",
    ] {
        write(root, path, &tools_schema, check)?;
    }
    let operation_schema = serde_json::to_value(clapham::schema::operation_schema())?;
    let mut descriptor = operation_schema.clone();
    let definitions = descriptor
        .as_object_mut()
        .and_then(|descriptor| descriptor.remove("$defs"))
        .ok_or("Missing operation definitions")?;
    let mut operation_types =
        String::from("// Generated by cargo xtask bindings from Clapham's operation schema.\n");
    operation_types.push_str(&format!(
        "export type Operation = {};\n",
        type_expression(&descriptor)?
    ));
    for (name, schema) in definitions
        .as_object()
        .ok_or("Missing operation definitions")?
    {
        operation_types.push_str(&format!(
            "export type {name} = {};\n",
            type_expression(schema)?
        ));
    }
    write(
        root,
        "typescript/packages/flow/src/operation-contract.ts",
        &operation_types,
        check,
    )?;
    write(
        root,
        "typescript/packages/flow/schemas/operation.schema.json",
        &(serde_json::to_string_pretty(&operation_schema)? + "\n"),
        check,
    )?;
    let schema = battersea_flow::schema::contract_schema();
    let mut types =
        String::from("// Generated by cargo xtask bindings from battersea-flow's Rust contract.\n");
    for (name, schema) in schema["$defs"].as_object().ok_or("Missing definitions")? {
        types.push_str(&format!(
            "export type {name} = {};\n",
            type_expression(schema)?
        ));
    }
    write(
        root,
        "typescript/packages/flow/src/contract.ts",
        &types,
        check,
    )?;
    write(root, "typescript/packages/flow/src/defaults.ts", &format!(
        "// Generated by cargo xtask bindings.\nimport type {{ FlowExecutionLimits }} from './contract.js';\nexport const FLOW_DOCUMENT_VERSION = {};\nexport const DEFAULT_FLOW_EXECUTION_LIMITS = {} satisfies FlowExecutionLimits;\n",
        battersea_flow::document::FLOW_DOCUMENT_VERSION,
        serde_json::to_string_pretty(&battersea_flow::FlowExecutionLimits::default())?
    ), check)?;
    let schema = serde_json::to_string_pretty(&schema)? + "\n";
    for path in [
        "crates/battersea-flow/schemas/flow.schema.json",
        "typescript/packages/flow/schemas/flow.schema.json",
    ] {
        write(root, path, &schema, check)?;
    }
    let compatibility = fs::read_to_string(
        root.join("crates/battersea-flow/fixtures/token-type-compatibility.json"),
    )?;
    write(
        root,
        "typescript/packages/flow/fixtures/token-type-compatibility.json",
        &compatibility,
        check,
    )?;
    let flow: FlowDocument = serde_json::from_value(json!({
        "version": 3, "execution": battersea_flow::FlowExecutionPolicy { source_order: vec!["source".into()], limits: battersea_flow::FlowExecutionLimits::default() }, "flow_key": "example", "title": "Independent application", "whitespace_mode": "preserve",
        "nodes": [{"id": "source", "instance_name": "Source", "definition_name": "Echo", "parameter_values": {"label": "example"}}],
        "layout": {"editor.example": {"position": [12, 34], "viewport": {"zoom": 1.5}}},
        "metadata": {"application": {"tags": ["contract", "roundtrip"]}}
    }))?;
    let fixtures = format!("[\n{}\n]\n", serialize_canonical_document(&flow)?);
    for path in [
        "crates/battersea-flow/fixtures/flows.json",
        "typescript/packages/flow/fixtures/flows.json",
    ] {
        write(root, path, &fixtures, check)?;
    }
    write(root, "typescript/packages/flow/src/fixtures.ts", &format!("// Generated by cargo xtask bindings.\nimport type {{ FlowDocument }} from './contract.js';\nexport const flows = {} satisfies FlowDocument[];\n", fixtures.trim()), check)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::type_expression;
    use serde_json::json;

    #[test]
    fn an_object_schema_without_properties_is_a_string_keyed_dictionary() {
        assert_eq!(
            type_expression(&json!({"type": ["object", "boolean"]})).unwrap(),
            "{ [key: string]: unknown } | boolean"
        );
        assert_eq!(
            type_expression(&json!({"type": "object", "additionalProperties": false})).unwrap(),
            "{  }"
        );
        assert_eq!(
            type_expression(&json!({"type": "object", "properties": {"a": {"type": "string"}}}))
                .unwrap(),
            "{ \"a\"?: string }"
        );
    }
}
